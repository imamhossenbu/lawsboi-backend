# -*- coding: utf-8 -*-
"""Validate the Bangla files against the English data and regenerate data/bn/cpc.ts.

  data/bn/cpc/<ROMAN>.json          — First Schedule, one file per Order:  { "<rule>": {t, b} }
  data/bn/cpc-sections/<part>.json  — sections, one file per Part:         { "<section>": {t, b, f} }
`b` must line up with the English blocks and `f` with the footnotes."""
import json, io, os, re, sys
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "lib", "laws", "data")
problems = 0


def check(where, en_body, en_notes, t):
    global problems
    want, got = len(en_body), len(t.get("b", []))
    if want != got:
        print(f"  {where}: {got} blocks, English has {want}"); problems += 1
    want, got = len(en_notes), len(t.get("f", []))
    if want != got and (got or en_notes and "b" in t):
        print(f"  {where}: {got} footnotes, English has {want}"); problems += 1


def load(path):
    return json.load(io.open(path, encoding="utf-8"))


# ---- First Schedule ----------------------------------------------------------------------------
en = load(f"{ROOT}/cpc-first-schedule.json")
order = list(en.keys())
files = sorted((f[:-5] for f in os.listdir(f"{ROOT}/bn/cpc") if f.endswith(".json")), key=order.index)
for roman in files:
    tr = load(f"{ROOT}/bn/cpc/{roman}.json")
    rules = {r["n"]: r for r in en[roman]}
    for n, t in tr.items():
        if n not in rules:
            print(f"  {roman} r.{n}: not in English data"); problems += 1; continue
        check(f"{roman} r.{n}", rules[n].get("body", []), [], t)
    missing = [n for n in rules if n not in tr and rules[n].get("body")]
    if missing: print(f"  {roman}: untranslated rules {missing}")

# ---- Sections ----------------------------------------------------------------------------------
groups = load(f"{ROOT}/cpc-sections.json")
part_of = lambda gid: re.sub(r"^(part-\d+).*$", r"\1", gid)
by_part = {}
for g in groups:
    by_part.setdefault(part_of(g["id"]), {}).update({s["n"]: s for s in g["sections"]})
sec_dir = f"{ROOT}/bn/cpc-sections"
os.makedirs(sec_dir, exist_ok=True)
parts = [p for p in by_part if os.path.exists(f"{sec_dir}/{p}.json")]
done = 0
for p in parts:
    tr = load(f"{sec_dir}/{p}.json")
    for n, t in tr.items():
        s = by_part[p].get(n)
        if not s:
            print(f"  {p} s.{n}: not in English data"); problems += 1; continue
        check(f"s.{n}", s.get("body", []), s.get("notes", []), t)
    missing = [n for n in by_part[p] if n not in tr]
    if missing: print(f"  {p}: untranslated sections {missing}")
    done += len(by_part[p]) - len(missing)

ident = lambda name: re.sub(r"\W", "_", name)
lines = ['import type { Translation } from "../../types";', "",
         "// Unofficial Bangla translations of the CPC. Regenerated by scripts/sync_bn.py.",
         "// First Schedule, one JSON file per Order: { \"<rule id>\": { \"t\": title, \"b\": [block 1, …] } }.",
         "// Sections, one JSON file per Part: { \"<section>\": { \"t\", \"b\", \"f\": [footnote 1, …] } }.",
         "// `b` lines up with the English blocks; anything without an entry falls back to the English text.", ""]
lines += [f'import {r} from "./cpc/{r}.json";' for r in files]
lines += [f'import {ident(p)} from "./cpc-sections/{p}.json";' for p in parts]
lines += ["", "export const cpcScheduleBn: Record<string, Record<string, Translation>> = {"]
lines += [f"  {r}," for r in files] + ["};", ""]
lines += ["export const cpcSectionsBn: Record<string, Record<string, Translation>> = {"]
lines += [f'  "{p}": {ident(p)},' for p in parts] + ["};", ""]
io.open(f"{ROOT}/bn/cpc.ts", "w", encoding="utf-8").write("\n".join(lines))
total = sum(len(v) for v in by_part.values())
print(f"orders translated: {len(files)}/{len(order)}; sections translated: {done}/{total}; problems: {problems}")
sys.exit(1 if problems else 0)
